def render(palette, art):
    rows = [row for row in art.strip("\n").split("\n")]
    assert len(rows) == W and all(len(row) == W for row in rows), [len(row) for row in rows]
    image = Image.new("RGBA", (W + 2, W + 2), (0, 0, 0, 0))
    filled = set()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch != ".":
                image.putpixel((x + 1, y + 1), rgb(palette[ch]))
                filled.add((x + 1, y + 1))
    # 輪郭：絵の外側の隣（斜めは含めない）を暗い色で1ドット
    for (x, y) in list(filled):
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            p = (x + dx, y + dy)
            if p not in filled:
                image.putpixel(p, OUTLINE)
    return image

def main():
    images = {}
    for key, (palette, art) in ICONS.items():
        image = render(palette, art)
        path = ROOT / "assets" / "icons" / (key + ".png")
        path.parent.mkdir(parents=True, exist_ok=True)
        image.save(path)
        images[key] = image
    if "--sheet" in sys.argv:
        target = sys.argv[sys.argv.index("--sheet") + 1]
        scale, pad = 8, 12
        side = (W + 2) * scale
        sheet = Image.new("RGBA", (len(images) * (side + pad) + pad, side + pad * 2), (189, 182, 174, 255))
        for index, image in enumerate(images.values()):
            big = image.resize((side, side), Image.NEAREST)
            sheet.paste(big, (pad + index * (side + pad), pad), big)
        sheet.save(target)
    print(f"{len(images)} icons")

if __name__ == "__main__":
    main()
